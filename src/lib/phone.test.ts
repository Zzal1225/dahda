import { describe, expect, it } from "vitest";
import { normalizePhone } from "./phone";

describe("normalizePhone", () => {
  it.each([
    ["01012345678", "01012345678"],
    ["010-1234-5678", "01012345678"],
    ["010 1234 5678", "01012345678"],
    ["010.1234.5678", "01012345678"],
    ["(010) 1234-5678", "01012345678"],
    ["  010-1234-5678  ", "01012345678"],
    ["0111234567", "0111234567"],
    ["+82 10-1234-5678", "01012345678"],
    ["+82 010-1234-5678", "01012345678"],
    ["+821012345678", "01012345678"],
    ["02-123-4567", "021234567"],
    ["02-1234-5678", "0212345678"],
    ["031-123-4567", "0311234567"],
    ["070-1234-5678", "07012345678"],
    ["080-123-4567", "0801234567"],
    ["1588-1234", "15881234"],
  ])("%s → %s", (input, expected) => {
    expect(normalizePhone(input)).toBe(expected);
  });

  it.each([
    "",
    "   ",
    "abc",
    "010-1234-567",
    "010-1234-56789",
    "012-1234-5678",
    "1234567",
    "010-1234-567a",
    "연락처없음",
    "+1 202-555-0100",
    "0101234567890",
    "00-000-0000",
  ])("%j는 형식 오류다", (input) => {
    expect(normalizePhone(input)).toBeNull();
  });

  it("같은 번호의 표기가 달라도 같은 값이 된다", () => {
    const forms = ["010-1234-5678", "010 1234 5678", "+82 10 1234 5678"];
    expect(new Set(forms.map(normalizePhone)).size).toBe(1);
  });
});
