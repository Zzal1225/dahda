import { describe, expect, it } from "vitest";
import { formatPhone, formatWon, maskPhone } from "./format";

describe("formatWon", () => {
  it.each([
    [0, "₩0"],
    [999, "₩999"],
    [1000, "₩1,000"],
    [1234567, "₩1,234,567"],
    [-1500, "-₩1,500"],
  ])("%d → %s", (amount, expected) => {
    expect(formatWon(amount)).toBe(expected);
  });
});

describe("formatPhone", () => {
  it.each([
    ["01000000001", "010-0000-0001"],
    ["0212345678", "02-1234-5678"],
    ["021234567", "02-123-4567"],
    ["0311234567", "031-123-4567"],
    ["15881234", "1588-1234"],
    ["123456789012", "123456789012"],
  ])("%s → %s", (digits, expected) => {
    expect(formatPhone(digits)).toBe(expected);
  });
});

describe("maskPhone", () => {
  it.each([
    // 하이픈 없음(저장 형식)
    ["01000000001", "010-****-0001"],
    ["01012345678", "010-****-5678"],
    // 하이픈·공백이 섞인 입력
    ["010-1234-5678", "010-****-5678"],
    ["010 1234 5678", "010-****-5678"],
    // 10자리: 가운데가 3자리라 별도 3개
    ["0111234567", "011-***-4567"],
    ["0311234567", "031-***-4567"],
    ["0212345678", "02-****-5678"],
    ["021234567", "02-***-4567"],
    // 번호 형식이 아니면 끝 4자리만 남긴다
    ["15881234", "****1234"],
    ["123456789012", "********9012"],
    ["123", "***"],
    // 숫자가 아니면 아무것도 보이지 않는다
    ["", "****"],
    ["010-abcd-5678", "****"],
    ["+821012345678", "****"],
  ])("%s → %s", (value, expected) => {
    expect(maskPhone(value)).toBe(expected);
  });

  it("원래 번호의 가운데 자리가 결과에 남지 않는다", () => {
    expect(maskPhone("01098765432")).not.toContain("9876");
  });
});
